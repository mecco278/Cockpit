import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import { weekRange } from '../dates.js';
import { createSeed } from './fixtures/demo-workspace.js';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { mkdir, writeFile } from 'node:fs/promises';

const require = createRequire(import.meta.url);
const args = process.argv.slice(2);
const option = (key, fallback) => args.includes(key) ? args[args.indexOf(key) + 1] : fallback;
const packagePath = option('--playwright-path', process.env.PLAYWRIGHT_PACKAGE || 'playwright');
const executablePath = option('--browser-path', process.env.PROTOTYPE_BROWSER || 'C:/Program Files/Google/Chrome/Application/chrome.exe');
const origin = option('--url', 'http://127.0.0.1:4317');
const output = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../test-results');
await mkdir(output, { recursive: true });
const { chromium } = require(packagePath);
const browser = await chromium.launch({ headless: true, executablePath });
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, deviceScaleFactor: 1 });
const page = await context.newPage();
const errors = [], checks = [];
page.on('pageerror', error => errors.push(error.message));
const readState = () => page.evaluate(() => JSON.parse(localStorage.getItem('xingjin.prototype.workspace.v1')));
try {
  await page.goto(origin);
  await page.evaluate(state => localStorage.setItem('xingjin.prototype.workspace.v1', JSON.stringify(state)), createSeed());
  await page.reload();
  await page.screenshot({ path: path.join(output, 'today-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: '完成并记录：整理最小验证的条件清单', exact: true }).click();
  await page.locator('form [name="outcome"]').fill('保留了一页条件清单，写清输入条件与验收方式。');
  await page.locator('form [name="next"]').fill('补齐一组条件一致的基线记录。');
  await page.getByRole('button', { name: '保存进展并完成', exact: true }).click();
  let state = await readState();
  assert.equal(state.entries.length, 6);
  assert.equal(state.tasks.find(t => t.id === 't-r3').status, 'done');
  checks.push('完成行动并保存关联进展');
  await page.getByRole('button', { name: '进度记录', exact: true }).click();
  await page.getByRole('heading', { name: '完成：整理最小验证的条件清单', exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, 'progress-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: '进展回顾', exact: true }).click();
  await page.getByRole('heading', { name: '下一步先做什么', exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, 'weekly-decision.png'), fullPage: true });
  assert.equal((await readState()).reviews.length, 0);
  await page.locator('.decision-focus').getByRole('button', { name: '加入今日', exact: true }).click();
  await page.locator('.decision-focus').getByText('已在今日').waitFor();
  assert.equal((await readState()).tasks.length, state.tasks.length);
  await page.getByText('复盘快照与调整历史', { exact: true }).click();
  await page.getByRole('button', { name: '生成本次复盘', exact: true }).first().click();
  const range = weekRange();
  assert.equal(Number(await page.locator('.fact-grid strong').first().innerText()), state.entries.filter(e => e.projectId === 'p-research' && e.date >= range.start && e.date <= range.end).length);
  await page.getByRole('button', { name: '预览计划调整', exact: true }).click();
  await page.locator('fieldset input').first().fill('先整理验证条件检查表（体验修改）');
  await page.locator('fieldset input[type="checkbox"]').first().check();
  await page.getByRole('button', { name: '确认采纳并保存', exact: true }).click();
  state = await readState();
  assert.equal(state.tasks.length, 10);
  assert.equal(state.revisions.length, 1);
  assert.equal(state.tasks.find(t => t.title === '先整理验证条件检查表（体验修改）').today, true);
  checks.push('复盘来源统计、修改建议、采纳与调整历史');
  await page.screenshot({ path: path.join(output, 'review-desktop.png'), fullPage: true });
  await page.reload();
  assert.deepEqual(await readState(), state);
  checks.push('刷新恢复完整工作空间');
  await page.locator('.sidebar-projects [data-id="p-research"]').click();
  await page.getByRole('button', { name: '先整理验证条件检查表（体验修改）', exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, 'project-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: '数据与体验', exact: true }).click();
  const pendingDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出体验备份', exact: true }).click();
  const download = await pendingDownload;
  await download.saveAs(path.join(output, 'roundtrip-backup.json'));
  await page.locator('#import-file').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"format":"wrong"}') });
  assert.deepEqual(await readState(), state);
  await page.locator('#import-file').setInputFiles(path.join(output, 'roundtrip-backup.json'));
  await page.getByRole('button', { name: '确认恢复备份', exact: true }).click();
  assert.deepEqual(await readState(), state);
  checks.push('备份导出导入往返、非法导入不改写原数据');
  await page.getByRole('button', { name: '体验反馈', exact: true }).click();
  await page.locator('textarea[name="text"]').fill('希望进展提交后更明显地提示新记录位置。');
  await page.getByRole('button', { name: '保存体验反馈', exact: true }).click();
  assert.equal((await readState()).feedback.length, 1);
  checks.push('体验反馈保存');
  await page.locator('.sidebar-projects [data-id="p-research"]').click();
  await page.getByRole('tab', { name: '每周复盘', exact: true }).click();
  await page.getByRole('button', { name: '查看所选周复盘', exact: true }).click();
  await page.getByRole('heading', { name: '进展回顾', exact: true }).waitFor();
  checks.push('每周总结替代原里程碑入口，能够生成并查看');
  const responsive = [];
  for (const width of [320, 390, 768, 1024]) {
    await page.setViewportSize({ width, height: 900 });
    for (const hash of ['#today', '#project/p-research', '#progress', '#review/p-research']) {
      await page.goto(origin + '/' + hash);
      const dimensions = await page.evaluate(() => ({ viewport: innerWidth, content: document.documentElement.scrollWidth }));
      assert.ok(dimensions.content <= width + 1, `${width} ${hash} 出现横向溢出`);
      responsive.push({ width, hash, ...dimensions });
    }
  }
  checks.push('四种窄屏宽度、四个页面共16次横向溢出检查');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(origin + '/#today');
  await page.screenshot({ path: path.join(output, 'today-mobile.png'), fullPage: true });
  await page.getByRole('button', { name: '记进展', exact: true }).first().click();
  await page.screenshot({ path: path.join(output, 'entry-mobile.png'), fullPage: true });
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('dialog').count(), 0);
  checks.push('窄屏表单与 Escape 关闭');
  assert.deepEqual(errors, []);
  const report = { passed: true, time: new Date().toISOString(), browser: browser.version(), checks, responsive, errors };
  await writeFile(path.join(output, 'browser-report.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} finally { await browser.close(); }
